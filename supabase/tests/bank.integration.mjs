// Run with: node supabase/tests/bank.integration.mjs
// Requires @electric-sql/pglite. Uses an isolated in-memory PostgreSQL instance.
import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';

const base = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const db = new PGlite();
const ids = {
  ada: '00000000-0000-4000-8000-000000000001',
  ben: '00000000-0000-4000-8000-000000000002',
  cy: '00000000-0000-4000-8000-000000000003',
  unconfirmed: '00000000-0000-4000-8000-000000000004',
  orphan: '00000000-0000-4000-8000-000000000005',
};
const run = async (sql, params = []) => db.query(sql, params);
const one = async (sql, params = []) => (await run(sql, params)).rows[0];
const as = async (id, work) => {
  await run('set role authenticated');
  await run(`select set_config('request.jwt.claim.sub',$1,false)`, [id]);
  try { return await work(); }
  finally { await run('reset role'); await run(`select set_config('request.jwt.claim.sub','',false)`); }
};
const expectDenied = async (work, label) => {
  let failed = false;
  try { await work(); } catch { failed = true; }
  assert.equal(failed, true, `${label} should fail`);
};
const scalar = async (sql, params = []) => Object.values(await one(sql, params))[0];

try {
  await db.exec(`
    create role anon nologin;
    create role authenticated nologin;
    create role service_role nologin;
    create schema auth;
    create table auth.users (
      id uuid primary key,
      email text,
      email_confirmed_at timestamptz,
      raw_user_meta_data jsonb not null default '{}'
    );
    create function auth.uid() returns uuid language sql stable as $$
      select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid
    $$;
    create table public.profiles (
      id uuid primary key references auth.users(id) on delete cascade,
      username text not null unique,
      avatar_url text,
      time_balance numeric(10,2) default 0,
      created_at timestamptz default now(), updated_at timestamptz default now()
    );
    grant select(time_balance),update(time_balance) on public.profiles to authenticated;
    alter table public.profiles enable row level security;
    create policy "Public can view usernames" on public.profiles for select using (true);
    grant select on public.profiles to anon;
    create table public.offers (
      id bigint generated by default as identity primary key,
      created_at timestamptz default now(),title text,description text,category text,
      user_id uuid not null references public.profiles(id)
    );
    create table public.wants (
      id bigint generated by default as identity primary key,
      created_at timestamptz default now(),title text,description text,category text,
      user_id uuid not null references public.profiles(id),criteria text[] default '{}'
    );
    create table public.exchanges (
      id bigint generated by default as identity primary key,
      offer_id bigint references public.offers(id),want_id bigint references public.wants(id),
      provider_id uuid references public.profiles(id),requester_id uuid references public.profiles(id),
      status text default 'pending',time_credits numeric(5,2) not null
    );
    create table public.transactions (
      id bigint generated by default as identity primary key,
      exchange_id bigint references public.exchanges(id),amount numeric(5,2)
    );
    grant select,insert,update on public.exchanges,public.transactions to authenticated;
  `);
  await run(`insert into auth.users(id,email,email_confirmed_at) values
    ($1,'ada@example.test',now()),($2,'ben@example.test',now()),
    ($3,'orphan@example.test',now())`,[ids.ada,ids.ben,ids.orphan]);
  await run(`insert into public.profiles(id,username,time_balance) values
    ($1,'ada',1.50),($2,'ben',0)`,[ids.ada,ids.ben]);
  await run(`insert into public.offers(user_id,title,description,category)
    values($1,'Old offer','Preserved old listing','Repair')`,[ids.ben]);
  await run(`insert into public.offers(user_id,title,description,category)
    values($1,null,'An old listing with nullable snapshots',null)`,[ids.ben]);
  await run(`insert into public.wants(user_id,title,description,category)
    values($1,'Old want','Preserved old listing','Repair')`,[ids.ada]);
  await run(`insert into public.exchanges(offer_id,want_id,provider_id,requester_id,status,time_credits)
    values(1,1,$1,$2,'completed',1.50)`,[ids.ben,ids.ada]);
  await run(`insert into public.transactions(exchange_id,amount) values(1,1.50)`);
  await db.exec(await readFile(path.join(base,'inspect/preflight.sql'),'utf8'));
  for (const migration of ['migrations/20261014000100_bank_schema.sql','migrations/20261014000200_bank_rpcs.sql']) {
    await db.exec(await readFile(path.join(base,migration),'utf8'));
  }
  await db.exec(await readFile(path.join(base,'inspect/preflight.sql'),'utf8'));

  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.ada])),90);
  assert.equal(await scalar(`select has_column_privilege('authenticated','public.profiles','username','UPDATE')`),true);
  assert.equal(await scalar(`select has_column_privilege('authenticated','public.profiles','avatar_url','SELECT')`),true);
  assert.equal(await scalar(`select has_column_privilege('authenticated','public.profiles','time_balance','SELECT')`),false);
  assert.equal(await scalar(`select has_column_privilege('authenticated','public.profiles','time_balance','UPDATE')`),false);
  assert.equal(await scalar(`select has_table_privilege('authenticated','public.accounts','SELECT')`),true);
  assert.equal(await scalar(`select has_table_privilege('authenticated','public.accounts','UPDATE')`),false);
  assert.equal(Number(await scalar('select count(*) from public.legacy_exchanges')),1);
  assert.equal(Number(await scalar('select count(*) from public.transactions')),1);
  assert.equal(Number(await scalar(`select amount_minutes from public.ledger_entries where user_id=$1 and kind='opening'`,[ids.ada])),90);
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.ben])),0);
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.orphan])),0);
  assert.equal(Number(await scalar(`select count(*) from public.ledger_entries where user_id=$1 and kind='opening'`,[ids.orphan])),1);
  await run(`insert into auth.users(id,email,email_confirmed_at,raw_user_meta_data)
    values($1,'cy@example.test',now(),'{}')`,[ids.cy]);
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.cy])),120);
  assert.equal(Number(await scalar(`select amount_minutes from public.ledger_entries where user_id=$1 and kind='welcome'`,[ids.cy])),120);
  await run(`insert into auth.users(id,email,raw_user_meta_data)
    values($1,'unconfirmed@example.test','{}')`,[ids.unconfirmed]);
  await as(ids.unconfirmed, async () => {
    assert.equal(Number(await scalar('select count(*) from public.offers')),0);
    await expectDenied(() => run(`select public.bank_save_listing('offer',null,'Unauthorized offer','An unconfirmed member cannot post','Test','{}')`),'unconfirmed RPC');
    await expectDenied(() => run(`select * from public.bank_project_summaries()`),'unconfirmed summaries');
    await expectDenied(() => run(`select * from public.bank_account_summary()`),'unconfirmed account summary');
  });

  await as(ids.ada, async () => {
    assert.equal(Number(await scalar('select count(*) from public.accounts')),1);
    assert.equal(Number(await scalar('select count(*) from public.profiles')),5);
    await expectDenied(() => run('select time_balance from public.profiles where id=$1',[ids.ada]),'legacy column read');
    await expectDenied(() => run('update public.profiles set time_balance=999 where id=$1',[ids.ada]),'profile balance edit');
    await expectDenied(() => run(`insert into public.ledger_entries(user_id,amount_minutes,balance_after_minutes,kind,description)
      values($1,999,999,'fund','forgery')`,[ids.ada]),'forged ledger insert');
    await expectDenied(() => run('insert into public.member_roles(user_id,role) values($1,$2)',[ids.ada,'facilitator']),'role elevation');
    await expectDenied(() => run('select * from public.legacy_exchanges'),'legacy exchange read');
    await expectDenied(() => run('select * from public.transactions'),'legacy transaction read');
    await run(`update public.profiles set avatar_url='https://example.test/a.png' where id=$1`,[ids.ada]);
    await expectDenied(() => run(`select public.bank_request_exchange('offer',1,null,'Invalid minutes')`),'null exchange minutes');
    await expectDenied(() => run(`select public.bank_donate(null,'Invalid minutes',$1)`,['99999999-9999-4999-8999-999999999999']),'null donation minutes');
    await expectDenied(() => run(`select public.bank_request_fund(null,'Invalid fund amount')`),'null fund minutes');
    await expectDenied(() => run(`select public.bank_create_project('Test title','Long enough description','Test',null)`),'null project goal');
    await expectDenied(() => run(`select public.bank_save_listing('want',null,'Invalid criteria','Long enough description','Test',array['unknown'])`),'unknown criterion');
  });
  await run('set role anon');
  await expectDenied(() => run('select * from public.profiles'),'anonymous profile read');
  await expectDenied(() => run('select * from public.offers'),'anonymous marketplace read');
  await expectDenied(() => run('select public.bank_donate(1,null,$1)',['11111111-1111-4111-8111-111111111111']),'anonymous donation');
  await expectDenied(() => run('select * from public.bank_project_summaries()'),'anonymous project summaries');
  await expectDenied(() => run('select * from public.bank_account_summary()'),'anonymous account summary');
  assert.equal(Number(await scalar('select member_count from public.bank_public_summary()')),4);
  await run('reset role');

  const oldListingExchange = await as(ids.ada, () => scalar(
    `select public.bank_request_exchange('offer',2,5,'Old listing snapshot')`
  ));
  assert.deepEqual(await one('select title,category from public.exchanges where id=$1',[oldListingExchange]),
    { title:'Untitled', category:'Other' });
  await as(ids.ada, () => run(`select public.bank_exchange_action($1,'cancel')`,[oldListingExchange]));

  const offer = await as(ids.ben, () => scalar(
    `select public.bank_save_listing('offer',null,'Bike repair help','I can repair bicycles locally','Repair','{}')`
  ));
  const exchange = await as(ids.ada, () => scalar(
    `select public.bank_request_exchange('offer',$1,60,'Please help my bicycle')`,[offer]
  ));
  await as(ids.cy, async () => {
    assert.equal(Number(await scalar('select count(*) from public.exchanges where id=$1',[exchange])),0);
    assert.equal(Number(await scalar('select count(*) from public.exchange_messages where exchange_id=$1',[exchange])),0);
    await expectDenied(() => run(`select public.bank_exchange_action($1,'accept')`,[exchange]),'third-party accept');
  });
  await as(ids.ben, async () => {
    await run(`select public.bank_exchange_action($1,'accept')`,[exchange]);
    await run(`select public.bank_exchange_action($1,'confirm')`,[exchange]);
    await run(`select public.bank_exchange_action($1,'confirm')`,[exchange]);
  });
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.ada])),90);
  await as(ids.ada, async () => {
    const account = await one('select * from public.bank_account_summary()');
    assert.deepEqual([Number(account.balance_minutes),Number(account.reserved_minutes),Number(account.available_minutes)],[90,60,30]);
    await expectDenied(() => run(`select public.bank_donate(31,'Reserved funds',$1)`,['33333333-3333-4333-8333-333333333333']),'donation spends reserved minutes');
  });
  await as(ids.ada, () => run(`select public.bank_exchange_action($1,'confirm')`,[exchange]));
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.ada])),30);
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.ben])),60);
  assert.equal(Number(await scalar(`select count(*) from public.ledger_entries where exchange_id=$1`,[exchange])),2);
  assert.equal(await scalar('select status from public.exchanges where id=$1',[exchange]),'completed');
  await as(ids.ada, async () => {
    const account = await one('select * from public.bank_account_summary()');
    assert.deepEqual([Number(account.balance_minutes),Number(account.reserved_minutes),Number(account.available_minutes)],[30,0,30]);
  });
  await as(ids.ada, async () => {
    assert.equal(await scalar(`select public.bank_exchange_action($1,'confirm')`,[exchange]),exchange);
    await expectDenied(() => run(`select public.bank_give_kudos($1,array['unknown'],'Thank you')`,[exchange]),'unknown kudos label');
    await run(`select public.bank_give_kudos($1,array['Great Teacher'],'Thank you')`,[exchange]);
  });
  const overspend = await as(ids.ada, () => scalar(
    `select public.bank_request_exchange('offer',$1,40,'Another repair session')`,[offer]
  ));
  await as(ids.ben, () => expectDenied(
    () => run(`select public.bank_exchange_action($1,'accept')`,[overspend]),'overspend on acceptance'
  ));
  assert.equal(await scalar('select status from public.exchanges where id=$1',[overspend]),'pending');
  assert.equal(Number(await scalar('select count(*) from public.ledger_entries where exchange_id=$1',[overspend])),0);
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.ada])),30);
  await as(ids.ada, () => run(`select public.bank_exchange_action($1,'cancel')`,[overspend]));
  const reservation = await as(ids.ada, () => scalar(
    `select public.bank_request_exchange('offer',$1,20,'Reservation to cancel')`,[offer]
  ));
  await as(ids.ben, () => run(`select public.bank_exchange_action($1,'accept')`,[reservation]));
  await as(ids.ada, async () => {
    const account = await one('select * from public.bank_account_summary()');
    assert.deepEqual([Number(account.balance_minutes),Number(account.reserved_minutes),Number(account.available_minutes)],[30,20,10]);
    await expectDenied(() => run(`select public.bank_donate(15,'Reserved funds',$1)`,['44444444-4444-4444-8444-444444444444']),'second reserved donation');
    await run(`select public.bank_exchange_action($1,'cancel')`,[reservation]);
    const released = await one('select * from public.bank_account_summary()');
    assert.deepEqual([Number(released.balance_minutes),Number(released.reserved_minutes),Number(released.available_minutes)],[30,0,30]);
    await run(`select public.bank_donate(15,'After cancellation',$1)`,['44444444-4444-4444-8444-444444444444']);
  });
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.ada])),15);

  const requestId='11111111-1111-4111-8111-111111111111';
  const donation = await as(ids.ben, () => scalar(`select public.bank_donate(30,'For community care',$1)`,[requestId]));
  const donationRetry = await as(ids.ben, () => scalar(`select public.bank_donate(30,'For community care',$1)`,[requestId]));
  assert.equal(donationRetry,donation);
  assert.equal(Number(await scalar('select balance_minutes from public.community_fund where id=1')),45);
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.ben])),30);
  await as(ids.ben, () => expectDenied(() => run(`select public.bank_donate(31,'For community care',$1)`,[requestId]),'changed donation retry'));
  const fundRequest = await as(ids.ada, () => scalar(`select public.bank_request_fund(20,'Help with local transportation')`));
  await as(ids.ben, () => expectDenied(() => run(`select public.bank_review_fund($1,'approve')`,[fundRequest]),'untrusted approval'));
  await run(`insert into public.member_roles(user_id,role) values($1,'facilitator')`,[ids.ben]);
  await as(ids.ben, () => expectDenied(() => run(`select public.bank_review_fund($1,null)`,[fundRequest]),'null fund decision'));
  await as(ids.ben, () => run(`select public.bank_review_fund($1,'approve')`,[fundRequest]));
  assert.equal(Number(await scalar('select balance_minutes from public.community_fund where id=1')),25);
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.ada])),35);
  await as(ids.ben, () => expectDenied(() => run(`select public.bank_review_fund($1,'approve')`,[fundRequest]),'double approval'));
  const facilitatorOwnRequest = await as(ids.ben, () => scalar(
    `select public.bank_request_fund(5,'My own private fund request')`
  ));
  await as(ids.ben, () => expectDenied(
    () => run(`select public.bank_review_fund($1,'approve')`,[facilitatorOwnRequest]),'self approval'
  ));

  const project = await as(ids.ada, () => scalar(`select public.bank_create_project('Neighborhood garden','We are building a shared garden','Outdoors',600)`));
  const contributionKey='22222222-2222-4222-8222-222222222222';
  const contribution = await as(ids.cy, () => scalar(`select public.bank_contribute_project($1,90,'Planted seedlings',$2)`,[project,contributionKey]));
  const contributionRetry = await as(ids.cy, () => scalar(`select public.bank_contribute_project($1,90,'Planted seedlings',$2)`,[project,contributionKey]));
  assert.equal(contributionRetry,contribution);
  assert.equal(Number(await scalar('select sum(minutes) from public.project_contributions where project_id=$1',[project])),90);
  await as(ids.ada, async () => {
    const summary = await one('select * from public.bank_project_summaries() where project_id=$1',[project]);
    assert.equal(Number(summary.current_minutes),90);
    assert.equal(Number(summary.contributor_count),1);
  });
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.cy])),120);
  await as(ids.cy, () => run(`select public.bank_set_urgent_opt_in(true)`));
  const want = await as(ids.ada, () => scalar(`select public.bank_save_listing('want',null,'Need a ride','A ride to an appointment','Transport','{}')`));
  await as(ids.ada, () => run(`select public.bank_amplify_want($1)`,[want]));
  await as(ids.ada, () => expectDenied(() => run(`select public.bank_amplify_want($1)`,[want]),'urgent cooldown'));
  assert.equal(Number(await scalar(`select count(*) from public.notifications where user_id=$1 and title='Urgent community request'`,[ids.cy])),1);
  const wantResponse = await as(ids.ben, () => scalar(
    `select public.bank_request_exchange('want',$1,30,'I can drive you')`,[want]
  ));
  await as(ids.ben, () => expectDenied(
    () => run(`select public.bank_exchange_action($1,'accept')`,[wantResponse]),'initiator accepts own want response'
  ));
  await as(ids.ada, () => run(`select public.bank_exchange_action($1,'accept')`,[wantResponse]));
  await as(ids.ben, () => run(`select public.bank_exchange_action($1,'confirm')`,[wantResponse]));
  await as(ids.ada, () => run(`select public.bank_exchange_action($1,'confirm')`,[wantResponse]));
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.ada])),5);
  assert.equal(Number(await scalar('select balance_minutes from public.accounts where user_id=$1',[ids.ben])),60);
  assert.equal(Number(await scalar(`select contributed_minutes from public.bank_public_summary()`)),180);
  console.log('Bank integration/security tests passed');
} finally {
  await db.close();
}
