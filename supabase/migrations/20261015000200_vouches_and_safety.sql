-- Vouches, Known suggestions, and the first-meeting safety card: Phase 2 of
-- docs/STANDING_AND_SAFETY_PLAN.md. Apply after 20261015000100_standing.sql.
begin;

-- A vouch is a sentence, not a click. The sentence and the voucher's name are
-- shown to members. The "comfortable in your home?" answer is for stewards only,
-- so that column is not granted to members; stewards read it through an RPC.
create table if not exists public.vouches (
  id bigint generated by default as identity primary key,
  voucher_id uuid not null references public.profiles(id) on delete cascade,
  member_id uuid not null references public.profiles(id) on delete cascade,
  sentence text not null check (char_length(sentence) between 10 and 300),
  basis text not null check (basis in ('met','exchange')),
  home_answer text not null check (home_answer in ('yes','no','not_sure')),
  created_at timestamptz not null default now(),
  unique (voucher_id, member_id),
  check (voucher_id <> member_id)
);
create index if not exists vouches_by_member on public.vouches(member_id);

-- First-meeting card answers are shared only between the two people.
create table if not exists public.exchange_first_meetings (
  exchange_id bigint not null references public.exchanges(id) on delete cascade,
  member_id uuid not null references public.profiles(id) on delete cascade,
  meet_place text not null default '' check (char_length(meet_place) <= 300),
  who_knows text not null default '' check (char_length(who_knows) <= 300),
  check_in_time text not null default '' check (char_length(check_in_time) <= 120),
  updated_at timestamptz not null default now(),
  primary key (exchange_id, member_id)
);

-- Check-ins and after-exchange notes are seen by the writer and by stewards
-- who are not part of that exchange. The other person never sees them.
create table if not exists public.exchange_safety_checkins (
  id bigint generated by default as identity primary key,
  exchange_id bigint not null references public.exchanges(id) on delete cascade,
  member_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null check (kind in ('fine','call_me')),
  created_at timestamptz not null default now()
);
create table if not exists public.exchange_steward_notes (
  exchange_id bigint not null references public.exchanges(id) on delete cascade,
  member_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now(),
  primary key (exchange_id, member_id)
);

alter table public.vouches enable row level security;
alter table public.exchange_first_meetings enable row level security;
alter table public.exchange_safety_checkins enable row level security;
alter table public.exchange_steward_notes enable row level security;
do $$ declare r record; begin
  for r in select schemaname,tablename,policyname from pg_policies
           where schemaname='public' and tablename = any(array[
             'vouches','exchange_first_meetings','exchange_safety_checkins','exchange_steward_notes']) loop
    execute format('drop policy %I on %I.%I',r.policyname,r.schemaname,r.tablename);
  end loop;
end $$;
create policy vouches_members on public.vouches for select to authenticated
  using (public.bank_is_member());
create policy first_meetings_participants on public.exchange_first_meetings for select to authenticated
  using (public.bank_is_member() and exists (
    select 1 from public.exchanges e where e.id=exchange_id and auth.uid() in (e.provider_id,e.requester_id)
  ));
create policy safety_checkins_private on public.exchange_safety_checkins for select to authenticated
  using (public.bank_is_member() and (member_id=auth.uid() or (public.bank_is_steward() and not exists (
    select 1 from public.exchanges e where e.id=exchange_id and auth.uid() in (e.provider_id,e.requester_id)
  ))));
create policy steward_notes_private on public.exchange_steward_notes for select to authenticated
  using (public.bank_is_member() and (member_id=auth.uid() or (public.bank_is_steward() and not exists (
    select 1 from public.exchanges e where e.id=exchange_id and auth.uid() in (e.provider_id,e.requester_id)
  ))));

revoke all on public.vouches,public.exchange_first_meetings,public.exchange_safety_checkins,
  public.exchange_steward_notes from public,anon,authenticated;
grant select(id,voucher_id,member_id,sentence,basis,created_at) on public.vouches to authenticated;
grant select on public.exchange_first_meetings,public.exchange_safety_checkins,
  public.exchange_steward_notes to authenticated;
do $$ declare r record; begin
 for r in select sn.nspname as sequence_schema,s.relname as sequence_name
          from pg_class s
          join pg_namespace sn on sn.oid=s.relnamespace
          join pg_depend d on d.objid=s.oid and d.deptype in ('a','i')
          join pg_class t on t.oid=d.refobjid
          join pg_namespace tn on tn.oid=t.relnamespace
          where s.relkind='S' and sn.nspname='public' and tn.nspname='public'
            and t.relname=any(array['vouches','exchange_safety_checkins']) loop
   execute format('revoke all on sequence %I.%I from public,anon,authenticated',r.sequence_schema,r.sequence_name);
 end loop;
end $$;

-- Only vouches from members who are Known or Steward right now count.
create or replace function public.bank_known_facts(p_member uuid)
returns table(days_member integer,completed_exchanges integer,exchange_partners integer,vouches integer,unresolved_concerns integer)
language sql stable security definer set search_path = '' as $$
 select floor(extract(epoch from (now()-coalesce(p.created_at,now())))/86400)::integer,
        (select count(*)::integer from public.exchanges e
         where e.status='completed' and p_member in (e.provider_id,e.requester_id)),
        (select count(distinct case when e.provider_id=p_member then e.requester_id else e.provider_id end)::integer
         from public.exchanges e where e.status='completed' and p_member in (e.provider_id,e.requester_id)),
        (select count(*)::integer from public.vouches v
         where v.member_id=p_member and public.bank_level_of(v.voucher_id) in ('known','steward')
           and not public.bank_is_paused(v.voucher_id)),
        (select count(*)::integer from public.concerns c where c.about_id=p_member and c.status<>'closed')
 from public.profiles p where p.id=p_member
$$;

create or replace function public.bank_completed_together(p_a uuid,p_b uuid)
returns boolean language sql stable security definer set search_path = '' as $$
 select exists(select 1 from public.exchanges e where e.status='completed'
               and ((e.provider_id=p_a and e.requester_id=p_b) or (e.provider_id=p_b and e.requester_id=p_a)))
$$;

create or replace function public.bank_vouch(p_member_id uuid,p_sentence text,p_basis text,p_home_answer text,p_not_household boolean)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_actor(); v_id bigint;
begin
 if public.bank_level_of(v_actor) not in ('known','steward') or public.bank_is_paused(v_actor) then
   raise exception 'Known neighbors and stewards can vouch for others.';
 end if;
 if p_member_id is null or p_member_id=v_actor then raise exception 'You cannot vouch for yourself.'; end if;
 if not public.bank_is_confirmed(p_member_id) then raise exception 'Member not found.'; end if;
 if char_length(btrim(coalesce(p_sentence,''))) not between 10 and 300 then raise exception 'Please write one sentence, 10 to 300 characters.'; end if;
 if p_basis is null or p_basis not in ('met','exchange') then raise exception 'Say how you know this person.'; end if;
 if p_home_answer is null or p_home_answer not in ('yes','no','not_sure') then raise exception 'Please answer the question about your home.'; end if;
 if p_not_household is not true then raise exception 'Nobody vouches for someone who lives with them.'; end if;
 if p_basis='exchange' and not public.bank_completed_together(v_actor,p_member_id) then
   raise exception 'You have not finished an exchange with this member yet.';
 end if;
 insert into public.vouches(voucher_id,member_id,sentence,basis,home_answer)
 values(v_actor,p_member_id,btrim(p_sentence),p_basis,p_home_answer)
 on conflict (voucher_id,member_id) do nothing returning id into v_id;
 if v_id is null then raise exception 'You already vouched for this member.'; end if;
 insert into public.notifications(user_id,title,body)
 values(p_member_id,'A neighbor vouched for you',
        coalesce((select username from public.profiles where id=v_actor),'A member')||' wrote a few words about you. They show on your standing.');
 return v_id;
end $$;

create or replace function public.bank_withdraw_vouch(p_member_id uuid)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_actor(); v_id bigint;
begin
 delete from public.vouches where voucher_id=v_actor and member_id=p_member_id returning id into v_id;
 if v_id is null then raise exception 'Vouch not found.'; end if;
 return v_id;
end $$;

-- Stewards see the private home answer, vouches given both ways on the same
-- day, and whether a member's vouchers already know each other.
create or replace function public.bank_steward_vouches()
returns table(id bigint,voucher_id uuid,member_id uuid,home_answer text,mutual_same_day boolean,created_at timestamptz)
language plpgsql stable security definer set search_path = '' as $$
#variable_conflict use_column
begin
 perform public.bank_require_steward();
 return query
 select v.id,v.voucher_id,v.member_id,v.home_answer,
        exists(select 1 from public.vouches r where r.voucher_id=v.member_id and r.member_id=v.voucher_id
               and r.created_at::date=v.created_at::date),
        v.created_at
 from public.vouches v
 where v.member_id<>auth.uid()
 order by v.created_at desc limit 500;
end $$;

-- Known is computed as a suggestion. A steward still confirms it.
create or replace function public.bank_known_suggestions()
returns table(member_id uuid,days_member integer,completed_exchanges integer,exchange_partners integer,vouches integer,vouchers_connected boolean)
language plpgsql stable security definer set search_path = '' as $$
#variable_conflict use_column
declare v_actor uuid := public.bank_require_steward();
begin
 return query
 select s.user_id,f.days_member,f.completed_exchanges,f.exchange_partners,f.vouches,
        exists(select 1 from public.vouches a join public.vouches b on a.member_id=s.user_id and b.member_id=s.user_id
                 and a.voucher_id<b.voucher_id
               where exists(select 1 from public.vouches x where (x.voucher_id=a.voucher_id and x.member_id=b.voucher_id)
                                                          or (x.voucher_id=b.voucher_id and x.member_id=a.voucher_id))
                  or public.bank_completed_together(a.voucher_id,b.voucher_id))
 from public.member_standing s
 cross join lateral public.bank_known_facts(s.user_id) f
 where s.level='introduced' and s.user_id<>v_actor and public.bank_known_ready(s.user_id);
end $$;

create or replace function public.bank_save_first_meeting(p_exchange_id bigint,p_meet_place text,p_who_knows text,p_check_in_time text)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_actor(); e public.exchanges%rowtype; v_other uuid;
begin
 select * into e from public.exchanges where id=p_exchange_id;
 if not found or v_actor not in (e.provider_id,e.requester_id) then raise exception 'Exchange not found'; end if;
 if e.status not in ('pending','accepted') then raise exception 'This exchange is closed.'; end if;
 if char_length(btrim(coalesce(p_meet_place,'')))>300 or char_length(btrim(coalesce(p_who_knows,'')))>300
    or char_length(btrim(coalesce(p_check_in_time,'')))>120 then raise exception 'That answer is too long.'; end if;
 insert into public.exchange_first_meetings(exchange_id,member_id,meet_place,who_knows,check_in_time,updated_at)
 values(p_exchange_id,v_actor,btrim(coalesce(p_meet_place,'')),btrim(coalesce(p_who_knows,'')),btrim(coalesce(p_check_in_time,'')),now())
 on conflict (exchange_id,member_id) do update set meet_place=excluded.meet_place,who_knows=excluded.who_knows,
   check_in_time=excluded.check_in_time,updated_at=now();
 v_other:=case when v_actor=e.provider_id then e.requester_id else e.provider_id end;
 insert into public.notifications(user_id,title,body) values(v_other,'First-meeting plan updated',e.title);
 return p_exchange_id;
end $$;

-- "Please have a steward call me" sends an in-app notice to stewards who are
-- not part of the exchange. It is not an emergency service; the page says so.
create or replace function public.bank_safety_checkin(p_exchange_id bigint,p_kind text)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_actor(); e public.exchanges%rowtype; v_id bigint;
begin
 if p_kind is null or p_kind not in ('fine','call_me') then raise exception 'Choose a check-in.'; end if;
 select * into e from public.exchanges where id=p_exchange_id;
 if not found or v_actor not in (e.provider_id,e.requester_id) then raise exception 'Exchange not found'; end if;
 if e.status<>'accepted' then raise exception 'Check-ins are for accepted exchanges.'; end if;
 insert into public.exchange_safety_checkins(exchange_id,member_id,kind)
 values(p_exchange_id,v_actor,p_kind) returning id into v_id;
 if p_kind='call_me' then
   perform public.bank_notify_stewards('A member asked a steward to call them',
     coalesce((select username from public.profiles where id=v_actor),'A member')||' asked for a call during an exchange. Please reach them soon.',
     array[e.provider_id,e.requester_id]);
 end if;
 return v_id;
end $$;

create or replace function public.bank_exchange_steward_note(p_exchange_id bigint,p_body text)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_actor(); e public.exchanges%rowtype;
begin
 if char_length(btrim(coalesce(p_body,''))) not between 1 and 2000 then raise exception 'Please write 1 to 2000 characters.'; end if;
 select * into e from public.exchanges where id=p_exchange_id;
 if not found or v_actor not in (e.provider_id,e.requester_id) then raise exception 'Exchange not found'; end if;
 if not (e.status='completed' or (e.status='accepted' and
         ((v_actor=e.provider_id and e.provider_confirmed) or (v_actor=e.requester_id and e.requester_confirmed)))) then
   raise exception 'You can leave a note after you confirm the exchange.';
 end if;
 insert into public.exchange_steward_notes(exchange_id,member_id,body)
 values(p_exchange_id,v_actor,btrim(p_body))
 on conflict (exchange_id,member_id) do update set body=excluded.body,created_at=now();
 perform public.bank_notify_stewards('A member left a private note for stewards',
   'It is about a finished exchange. Open your steward desk to read it.',array[e.provider_id,e.requester_id]);
 return p_exchange_id;
end $$;

-- Stewards cannot read exchanges they are not part of, so this gives them the
-- few details needed to follow up on a call request or a private note.
create or replace function public.bank_steward_safety_feed()
returns table(kind text,exchange_id bigint,member_id uuid,other_id uuid,title text,body text,created_at timestamptz)
language plpgsql stable security definer set search_path = '' as $$
#variable_conflict use_column
declare v_actor uuid := public.bank_require_steward();
begin
 return query
 select * from (
   select 'call_me'::text,c.exchange_id,c.member_id,
          case when c.member_id=e.provider_id then e.requester_id else e.provider_id end,
          e.title,null::text,c.created_at
   from public.exchange_safety_checkins c join public.exchanges e on e.id=c.exchange_id
   where c.kind='call_me' and v_actor not in (e.provider_id,e.requester_id)
   union all
   select 'note'::text,n.exchange_id,n.member_id,
          case when n.member_id=e.provider_id then e.requester_id else e.provider_id end,
          e.title,n.body,n.created_at
   from public.exchange_steward_notes n join public.exchanges e on e.id=n.exchange_id
   where v_actor not in (e.provider_id,e.requester_id)
 ) feed order by 7 desc limit 100;
end $$;

do $$ declare r record; begin
 for r in select p.oid::regprocedure as signature from pg_proc p join pg_namespace n on n.oid=p.pronamespace
          where n.nspname='public' and p.proname = any(array[
            'bank_known_facts','bank_completed_together','bank_vouch','bank_withdraw_vouch',
            'bank_steward_vouches','bank_known_suggestions','bank_save_first_meeting',
            'bank_safety_checkin','bank_exchange_steward_note','bank_steward_safety_feed']) loop
   execute format('revoke all on function %s from public,anon,authenticated',r.signature);
 end loop;
end $$;
grant execute on function
  public.bank_vouch(uuid,text,text,text,boolean),
  public.bank_withdraw_vouch(uuid),
  public.bank_steward_vouches(),
  public.bank_known_suggestions(),
  public.bank_save_first_meeting(bigint,text,text,text),
  public.bank_safety_checkin(bigint,text),
  public.bank_exchange_steward_note(bigint,text),
  public.bank_steward_safety_feed()
to authenticated;
commit;
