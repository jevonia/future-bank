-- Standing and introductions: Phase 1 of docs/STANDING_AND_SAFETY_PLAN.md.
-- Apply after 20261014000200_bank_rpcs.sql, on a backup or preview first.
-- Levels are words on the site (New, Introduced, Known, Steward). A level says
-- how well the community knows someone. It never grants or removes access to
-- the bank itself, and no level changes without a named steward.
begin;

create table if not exists public.gatherings (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 3 and 120),
  starts_at timestamptz not null,
  location text not null check (char_length(location) between 3 and 300),
  host_id uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);
create index if not exists gatherings_by_start on public.gatherings(starts_at desc);

-- One row per member who has moved past New. A missing row means New.
-- Introduction details are kept apart from the current level so "Met by Nova
-- at the October repair day" survives later steps.
create table if not exists public.member_standing (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  level text not null check (level in ('new','introduced','known','steward')),
  since timestamptz not null default now(),
  granted_by uuid references public.profiles(id) on delete set null,
  introduced_by uuid references public.profiles(id) on delete set null,
  introduced_at timestamptz,
  introduced_gathering_id bigint references public.gatherings(id) on delete set null,
  steward_renew_by date,
  check ((level = 'steward') = (steward_renew_by is not null))
);

-- Humans decide; software remembers. Every change says who and why. Seen by
-- the member it is about and by stewards.
create table if not exists public.standing_events (
  id bigint generated by default as identity primary key,
  member_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null check (kind in ('level','pause','unpause','renewal')),
  from_level text,
  to_level text,
  changed_by uuid references public.profiles(id) on delete set null,
  reason text not null check (char_length(reason) between 3 and 500),
  created_at timestamptz not null default now()
);
create index if not exists standing_events_by_member on public.standing_events(member_id,created_at desc);

create table if not exists public.gathering_checkins (
  gathering_id bigint not null references public.gatherings(id) on delete cascade,
  member_id uuid not null references public.profiles(id) on delete cascade,
  steward_id uuid references public.profiles(id) on delete set null,
  checked_in_at timestamptz not null default now(),
  primary key (gathering_id, member_id)
);

create table if not exists public.concerns (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references public.profiles(id) on delete cascade,
  about_id uuid references public.profiles(id) on delete set null,
  exchange_id bigint references public.exchanges(id) on delete set null,
  body text not null check (char_length(body) between 10 and 4000),
  share_name boolean not null default false,
  status text not null default 'open' check (status in ('open','responded','closed')),
  response text check (char_length(response) between 1 and 2000),
  responded_by uuid references public.profiles(id) on delete set null,
  responded_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  check (about_id is null or about_id <> reporter_id)
);
create index if not exists concerns_by_about on public.concerns(about_id) where status <> 'closed';

-- Working notes stay with stewards. The reporter sees only the reply.
create table if not exists public.concern_notes (
  id bigint generated by default as identity primary key,
  concern_id bigint not null references public.concerns(id) on delete cascade,
  steward_id uuid references public.profiles(id) on delete set null,
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);

create table if not exists public.standing_pauses (
  member_id uuid primary key references public.profiles(id) on delete cascade,
  paused_by uuid references public.profiles(id) on delete set null,
  concern_id bigint references public.concerns(id) on delete set null,
  reason text not null check (char_length(reason) between 3 and 500),
  paused_at timestamptz not null default now()
);

create table if not exists public.steward_nominations (
  member_id uuid not null references public.profiles(id) on delete cascade,
  nominated_by uuid not null references public.profiles(id) on delete cascade,
  reason text not null check (char_length(reason) between 3 and 500),
  created_at timestamptz not null default now(),
  primary key (member_id, nominated_by),
  check (member_id <> nominated_by)
);

alter table public.offers add column if not exists min_standing text not null default 'anyone';
alter table public.wants add column if not exists min_standing text not null default 'anyone';
do $$ begin
 if not exists(select 1 from pg_constraint where conrelid='public.offers'::regclass and conname='offers_min_standing') then
   alter table public.offers add constraint offers_min_standing check (min_standing in ('anyone','introduced','known'));
 end if;
 if not exists(select 1 from pg_constraint where conrelid='public.wants'::regclass and conname='wants_min_standing') then
   alter table public.wants add constraint wants_min_standing check (min_standing in ('anyone','introduced','known'));
 end if;
end $$;

-- Backfill: the facilitator role becomes Steward. Everyone else starts as New
-- until a steward meets them; nobody is marked Introduced by guesswork.
insert into public.member_standing(user_id,level,since,steward_renew_by)
select r.user_id,'steward',now(),(now()+interval '1 year')::date
from public.member_roles r where r.role='facilitator'
on conflict (user_id) do nothing;
insert into public.standing_events(member_id,kind,from_level,to_level,reason)
select s.user_id,'level','new','steward','Founding steward: held the facilitator role when standing began'
from public.member_standing s
where s.level='steward' and not exists(select 1 from public.standing_events e where e.member_id=s.user_id);

create or replace function public.bank_level_rank(p_level text)
returns integer language sql immutable set search_path = '' as $$
 select case p_level when 'introduced' then 1 when 'known' then 2 when 'steward' then 3 else 0 end
$$;
create or replace function public.bank_level_of(p_member uuid)
returns text language sql stable security definer set search_path = '' as $$
 select coalesce((select level from public.member_standing where user_id=p_member),'new')
$$;
create or replace function public.bank_is_paused(p_member uuid)
returns boolean language sql stable security definer set search_path = '' as $$
 select exists(select 1 from public.standing_pauses where member_id=p_member)
$$;
create or replace function public.bank_is_active_steward(p_member uuid)
returns boolean language sql stable security definer set search_path = '' as $$
 select public.bank_level_of(p_member)='steward' and not public.bank_is_paused(p_member)
$$;
create or replace function public.bank_is_steward()
returns boolean language sql stable security definer set search_path = '' as $$
 select public.bank_is_member() and public.bank_is_active_steward(auth.uid())
$$;
create or replace function public.bank_require_steward()
returns uuid language plpgsql stable security definer set search_path = '' as $$
declare v_actor uuid := public.bank_actor();
begin
 if not public.bank_is_active_steward(v_actor) then
   raise exception 'Only a steward can do that.' using errcode='42501';
 end if;
 return v_actor;
end $$;
create or replace function public.bank_is_confirmed(p_member uuid)
returns boolean language sql stable security definer set search_path = '' as $$
 select exists(select 1 from public.profiles p join auth.users u on u.id=p.id
               where p.id=p_member and u.email_confirmed_at is not null)
$$;
-- A paused member meets no requirement above Anyone.
create or replace function public.bank_meets_minimum(p_member uuid,p_min text)
returns boolean language sql stable security definer set search_path = '' as $$
 select coalesce(p_min,'anyone')='anyone' or (
   not public.bank_is_paused(p_member)
   and public.bank_level_rank(public.bank_level_of(p_member)) >= public.bank_level_rank(p_min))
$$;

