create policy standing_members on public.member_standing for select to authenticated
  using (public.bank_is_member());
create policy standing_events_private on public.standing_events for select to authenticated
  using (public.bank_is_member() and (member_id=auth.uid() or public.bank_is_steward()));
create policy gatherings_members on public.gatherings for select to authenticated
  using (public.bank_is_member());
create policy checkins_private on public.gathering_checkins for select to authenticated
  using (public.bank_is_member() and (member_id=auth.uid() or public.bank_is_steward()));
-- A steward never sees a concern about themselves.
create policy concerns_private on public.concerns for select to authenticated
  using (public.bank_is_member() and (reporter_id=auth.uid() or
         (public.bank_is_steward() and about_id is distinct from auth.uid())));
create policy concern_notes_stewards on public.concern_notes for select to authenticated
  using (public.bank_is_steward() and exists (
    select 1 from public.concerns c where c.id=concern_id and c.about_id is distinct from auth.uid()
  ));
create policy pauses_private on public.standing_pauses for select to authenticated
  using (public.bank_is_member() and (member_id=auth.uid() or public.bank_is_steward()));
create policy nominations_stewards on public.steward_nominations for select to authenticated
  using (public.bank_is_steward());

revoke all on public.member_standing,public.standing_events,public.gatherings,
  public.gathering_checkins,public.concerns,public.concern_notes,public.standing_pauses,
  public.steward_nominations from public,anon,authenticated;
grant select on public.member_standing,public.standing_events,public.gatherings,
  public.gathering_checkins,public.concerns,public.concern_notes,public.standing_pauses,
  public.steward_nominations to authenticated;
do $$ declare r record; begin
 for r in select sn.nspname as sequence_schema,s.relname as sequence_name
          from pg_class s
          join pg_namespace sn on sn.oid=s.relnamespace
          join pg_depend d on d.objid=s.oid and d.deptype in ('a','i')
          join pg_class t on t.oid=d.refobjid
          join pg_namespace tn on tn.oid=t.relnamespace
          where s.relkind='S' and sn.nspname='public' and tn.nspname='public'
            and t.relname=any(array['gatherings','standing_events','concerns','concern_notes']) loop
   execute format('revoke all on sequence %I.%I from public,anon,authenticated',r.sequence_schema,r.sequence_name);
 end loop;
end $$;

-- Listings: "Who can say yes?" plus the "someone else present" criterion.
drop function if exists public.bank_save_listing(text,bigint,text,text,text,text[]);
create or replace function public.bank_save_listing(
  p_kind text,p_id bigint,p_title text,p_description text,p_category text,p_criteria text[],
  p_min_standing text default 'anyone'
) returns bigint language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_actor(); v_id bigint; v_min text := coalesce(p_min_standing,'anyone');
begin
 if p_kind not in ('offer','want') or p_kind is null then raise exception 'Invalid listing kind'; end if;
 if char_length(btrim(coalesce(p_title,''))) not between 3 and 120 or
    char_length(btrim(coalesce(p_description,''))) not between 10 and 4000 or
    char_length(btrim(coalesce(p_category,''))) not between 2 and 80 then
   raise exception 'Listing fields are outside allowed lengths'; end if;
 if v_min not in ('anyone','introduced','known') then raise exception 'Choose who can say yes'; end if;
 if coalesce(array_ndims(p_criteria),1)<>1 or
    coalesce(array_length(p_criteria,1),0)>19 or exists (
   select 1 from unnest(coalesce(p_criteria,'{}'::text[])) c
   where c is null or c <> all(array[
     'public_place','accessible','daytime_only','evening_only','weekend_only',
     'child_friendly','pet_friendly','wheelchair_accessible','quiet_environment',
     'outdoor','indoor','near_public_transit','parking_available',
     'flexible_schedule','one_time_only','ongoing_help','virtual_ok','in_person_only',
     'someone_else_present'
   ])
 ) then raise exception 'Invalid criteria'; end if;
 if p_kind='offer' then
   if p_id is null then
     insert into public.offers(user_id,title,description,category,min_standing)
     values(v_actor,btrim(p_title),btrim(p_description),btrim(p_category),v_min) returning id into v_id;
   else
     update public.offers set title=btrim(p_title),description=btrim(p_description),category=btrim(p_category),min_standing=v_min
     where id=p_id and user_id=v_actor and active returning id into v_id;
   end if;
 else
   if p_id is null then
     insert into public.wants(user_id,title,description,category,criteria,min_standing)
     values(v_actor,btrim(p_title),btrim(p_description),btrim(p_category),coalesce(p_criteria,'{}'),v_min) returning id into v_id;
   else
     update public.wants set title=btrim(p_title),description=btrim(p_description),category=btrim(p_category),
       criteria=coalesce(p_criteria,'{}'),min_standing=v_min
     where id=p_id and user_id=v_actor and active returning id into v_id;
   end if;
 end if;
 if v_id is null then raise exception 'Listing not found or not editable'; end if;
 return v_id;
end $$;

create or replace function public.bank_request_exchange(
  p_listing_kind text,p_listing_id bigint,p_minutes integer,p_note text
) returns bigint language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_actor(); v_owner uuid; v_provider uuid; v_requester uuid;
        v_title text; v_category text; v_id bigint; v_min text;
begin
 if p_minutes is null or p_minutes not between 1 and 2880 then raise exception 'Exchange must be 1–2880 minutes'; end if;
 if char_length(coalesce(p_note,''))>2000 then raise exception 'Note too long'; end if;
 if p_listing_kind='offer' then
   select user_id,title,category,min_standing into v_owner,v_title,v_category,v_min
   from public.offers where id=p_listing_id and active for share;
   v_provider:=v_owner; v_requester:=v_actor;
 elsif p_listing_kind='want' then
   select user_id,title,category,min_standing into v_owner,v_title,v_category,v_min
   from public.wants where id=p_listing_id and active for share;
   v_provider:=v_actor; v_requester:=v_owner;
 else raise exception 'Invalid listing kind'; end if;
 if v_owner is null or v_owner=v_actor then raise exception 'Active listing not found or owned by you'; end if;
 if public.bank_is_paused(v_actor) then
   raise exception 'A steward has asked to talk with you before your next exchange.';
 end if;
 if not public.bank_meets_minimum(v_actor,v_min) then
   if v_min='known' then
     raise exception 'This neighbor asked for Known neighbors only.';
   end if;
   raise exception 'This neighbor asked for members a steward has met in person. Come to a gathering to be introduced.';
 end if;
 v_title:=coalesce(nullif(btrim(v_title),''),'Untitled');
 v_category:=coalesce(nullif(btrim(v_category),''),'Other');
 insert into public.exchanges(offer_id,want_id,provider_id,requester_id,initiator_id,title,category,minutes)
 values(case when p_listing_kind='offer' then p_listing_id else null end,
        case when p_listing_kind='want' then p_listing_id else null end,
        v_provider,v_requester,v_actor,v_title,v_category,p_minutes)
 returning id into v_id;
 if nullif(btrim(coalesce(p_note,'')),'') is not null then
   insert into public.exchange_messages(exchange_id,sender_id,body)
   values(v_id,v_actor,btrim(p_note));
 end if;
 insert into public.notifications(user_id,title,body)
 values(v_owner,'New exchange request','A member requested an exchange for '||v_title);
 return v_id;
end $$;

-- Same as 20261014000200, plus two checks on accept: nobody with a paused
-- standing starts a new exchange, and the sender still meets the listing's
-- "Who can say yes?" setting.
create or replace function public.bank_exchange_action(p_id bigint,p_operation text)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_actor(); e public.exchanges%rowtype;
        v_payer integer; v_receiver integer; v_other uuid; v_reserved bigint; v_min text;
begin
 select * into e from public.exchanges where id=p_id for update;
 if not found or v_actor not in (e.provider_id,e.requester_id) then raise exception 'Exchange not found'; end if;
 v_other:=case when v_actor=e.provider_id then e.requester_id else e.provider_id end;
 if p_operation in ('accept','decline') then
   if e.status<>'pending' or v_actor=e.initiator_id then raise exception 'Only the invited member can respond to a pending exchange'; end if;
   if p_operation='accept' then
     if public.bank_is_paused(v_actor) then
       raise exception 'A steward has asked to talk with you before your next exchange.';
     end if;
     if public.bank_is_paused(e.initiator_id) then
       raise exception 'This exchange cannot go ahead right now. A steward can tell you more.';
     end if;
     if e.offer_id is not null then select min_standing into v_min from public.offers where id=e.offer_id;
     elsif e.want_id is not null then select min_standing into v_min from public.wants where id=e.want_id; end if;
     if not public.bank_meets_minimum(e.initiator_id,v_min) then
       raise exception 'This member no longer meets the "Who can say yes?" setting on your listing.';
     end if;
     -- The payer account serializes all reservations, donations, and settlements.
     select balance_minutes into v_payer from public.accounts
       where user_id=e.requester_id for update;
     if v_payer is null then raise exception 'Requester account not found'; end if;
     select coalesce(sum(minutes),0) into v_reserved from public.exchanges
       where requester_id=e.requester_id and status='accepted' and id<>e.id;
     if v_payer::bigint-v_reserved<e.minutes then
       raise exception 'Requester has insufficient available minutes';
     end if;
   end if;
   update public.exchanges set status=case when p_operation='accept' then 'accepted' else 'declined' end where id=p_id;
   insert into public.notifications(user_id,title,body)
   values(v_other,case when p_operation='accept' then 'Exchange accepted' else 'Exchange declined' end,e.title);
 elsif p_operation='cancel' then
   if e.status not in ('pending','accepted') then raise exception 'Exchange cannot be cancelled'; end if;
   if e.status='accepted' then
     perform 1 from public.accounts where user_id=e.requester_id for update;
   end if;
   update public.exchanges set status='cancelled' where id=p_id;
   insert into public.notifications(user_id,title,body) values(v_other,'Exchange cancelled',e.title);
 elsif p_operation='confirm' then
   if e.status='completed' and
      ((v_actor=e.provider_id and e.provider_confirmed) or
       (v_actor=e.requester_id and e.requester_confirmed)) then
     return p_id;
   end if;
   if e.status<>'accepted' then raise exception 'Only accepted exchanges can be confirmed'; end if;
   if v_actor=e.provider_id and e.provider_confirmed or
      v_actor=e.requester_id and e.requester_confirmed then return p_id; end if;
   if v_actor=e.provider_id then e.provider_confirmed:=true;
   else e.requester_confirmed:=true; end if;
   update public.exchanges set provider_confirmed=e.provider_confirmed,
     requester_confirmed=e.requester_confirmed where id=p_id;
   if e.provider_confirmed and e.requester_confirmed then
     -- Stable UUID ordering prevents opposite-direction exchanges deadlocking.
     perform 1 from public.accounts where user_id in (e.provider_id,e.requester_id)
       order by user_id for update;
     select balance_minutes into v_payer from public.accounts where user_id=e.requester_id;
     select balance_minutes into v_receiver from public.accounts where user_id=e.provider_id;
     if v_payer is null or v_receiver is null or v_payer<e.minutes then
       raise exception 'Requester has insufficient minutes or an account is missing';
     end if;
     update public.accounts set balance_minutes=v_payer-e.minutes where user_id=e.requester_id;
     update public.accounts set balance_minutes=v_receiver+e.minutes where user_id=e.provider_id;
     insert into public.ledger_entries(user_id,amount_minutes,balance_after_minutes,kind,exchange_id,description)
     values(e.requester_id,-e.minutes,v_payer-e.minutes,'exchange',p_id,'Exchange: '||e.title),
           (e.provider_id,e.minutes,v_receiver+e.minutes,'exchange',p_id,'Exchange: '||e.title);
     update public.exchanges set status='completed',completed_at=now() where id=p_id;
     insert into public.notifications(user_id,title,body)
     values(e.requester_id,'Exchange completed',e.title),(e.provider_id,'Exchange completed',e.title);
   else
     insert into public.notifications(user_id,title,body) values(v_other,'Completion confirmation',e.title);
   end if;
 else raise exception 'Invalid exchange operation'; end if;
 return p_id;
end $$;

-- Notify every active steward except the people a notice is about.
create or replace function public.bank_notify_stewards(p_title text,p_body text,p_except uuid[])
returns void language sql security definer set search_path = '' as $$
 insert into public.notifications(user_id,title,body)
 select s.user_id,p_title,p_body from public.member_standing s
 where s.level='steward' and not public.bank_is_paused(s.user_id)
   and s.user_id <> all(coalesce(p_except,'{}'::uuid[]))
$$;

create or replace function public.bank_create_gathering(p_title text,p_starts_at timestamptz,p_location text)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_require_steward(); v_id bigint;
begin
 if char_length(btrim(coalesce(p_title,''))) not between 3 and 120 then raise exception 'Gathering name must be 3 to 120 characters.'; end if;
 if char_length(btrim(coalesce(p_location,''))) not between 3 and 300 then raise exception 'Place must be 3 to 300 characters.'; end if;
 -- Past dates are allowed so paper sign-in sheets can be entered later.
 if p_starts_at is null or p_starts_at < now()-interval '90 days' or p_starts_at > now()+interval '366 days' then
   raise exception 'Choose a date within the past 90 days or the next year.';
 end if;
 insert into public.gatherings(title,starts_at,location,host_id)
 values(btrim(p_title),p_starts_at,btrim(p_location),v_actor) returning id into v_id;
 if p_starts_at > now() then
   insert into public.notifications(user_id,title,body)
   select p.id,'New community gathering',btrim(p_title)||'. See the date and place on your dashboard.'
   from public.profiles p join auth.users u on u.id=p.id
   where u.email_confirmed_at is not null and p.id<>v_actor;
 end if;
 return v_id;
end $$;

-- A steward's check-in at a gathering is what makes a New member Introduced.
create or replace function public.bank_check_in(p_gathering_id bigint,p_member_id uuid)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_require_steward(); g public.gatherings%rowtype; v_level text;
begin
 select * into g from public.gatherings where id=p_gathering_id;
 if not found then raise exception 'Gathering not found.'; end if;
 if g.starts_at > now()+interval '12 hours' then raise exception 'Check-in opens on the day of the gathering.'; end if;
 if p_member_id is null or p_member_id=v_actor then raise exception 'Another steward checks you in.'; end if;
 if not public.bank_is_confirmed(p_member_id) then raise exception 'Member not found.'; end if;
 perform 1 from public.profiles where id=p_member_id for update;
 insert into public.gathering_checkins(gathering_id,member_id,steward_id)
 values(p_gathering_id,p_member_id,v_actor) on conflict do nothing;
 v_level:=public.bank_level_of(p_member_id);
 if v_level='new' then
   insert into public.member_standing(user_id,level,since,granted_by,introduced_by,introduced_at,introduced_gathering_id)
   values(p_member_id,'introduced',now(),v_actor,v_actor,now(),p_gathering_id)
   on conflict (user_id) do update set level='introduced',since=now(),granted_by=v_actor,
     introduced_by=v_actor,introduced_at=now(),introduced_gathering_id=p_gathering_id,steward_renew_by=null;
   insert into public.standing_events(member_id,kind,from_level,to_level,changed_by,reason)
   values(p_member_id,'level','new','introduced',v_actor,'Checked in at '||left(g.title,200));
   insert into public.notifications(user_id,title,body)
   values(p_member_id,'You are now Introduced','A steward checked you in at '||g.title||'.');
 end if;
 return p_gathering_id;
end $$;

create or replace function public.bank_known_facts(p_member uuid)
returns table(days_member integer,completed_exchanges integer,exchange_partners integer,vouches integer,unresolved_concerns integer)
language sql stable security definer set search_path = '' as $$
 select floor(extract(epoch from (now()-coalesce(p.created_at,now())))/86400)::integer,
        (select count(*)::integer from public.exchanges e
         where e.status='completed' and p_member in (e.provider_id,e.requester_id)),
        (select count(distinct case when e.provider_id=p_member then e.requester_id else e.provider_id end)::integer
         from public.exchanges e where e.status='completed' and p_member in (e.provider_id,e.requester_id)),
        0, -- Vouches arrive in 20261015000200.
        (select count(*)::integer from public.concerns c where c.about_id=p_member and c.status<>'closed')
 from public.profiles p where p.id=p_member
$$;
-- The Known thresholds are a starting guess (plan, open decision 3). Keep
-- KNOWN_RULES in src/lib/standing.ts in step with these numbers.
create or replace function public.bank_known_ready(p_member uuid)
returns boolean language sql stable security definer set search_path = '' as $$
 select coalesce((select f.days_member>=60 and f.completed_exchanges>=3 and f.exchange_partners>=2
                  and f.vouches>=2 and f.unresolved_concerns=0
                  from public.bank_known_facts(p_member) f),false)
   and public.bank_level_of(p_member)='introduced' and not public.bank_is_paused(p_member)
$$;
-- Members may see their own progress; open concerns are shown only to stewards.
create or replace function public.bank_known_progress(p_member uuid)
returns table(days_member integer,completed_exchanges integer,exchange_partners integer,vouches integer,unresolved_concerns integer,ready boolean)
language plpgsql stable security definer set search_path = '' as $$
#variable_conflict use_column
declare v_actor uuid := public.bank_actor(); v_steward boolean := public.bank_is_steward();
begin
 if p_member is null or (p_member<>v_actor and not v_steward) then raise exception 'Only you and the stewards can see this.'; end if;
 return query
 select f.days_member,f.completed_exchanges,f.exchange_partners,f.vouches,
        case when v_steward and p_member<>v_actor then f.unresolved_concerns end,
        case when v_steward and p_member<>v_actor then public.bank_known_ready(p_member) end
 from public.bank_known_facts(p_member) f;
end $$;

create or replace function public.bank_set_standing(p_member_id uuid,p_level text,p_reason text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_require_steward(); v_from text; v_reason text := btrim(coalesce(p_reason,''));
        v_noms integer; v_second timestamptz;
begin
 if p_level is null or p_level not in ('introduced','known','steward') then raise exception 'Choose Introduced, Known, or Steward.'; end if;
 if char_length(v_reason) not between 3 and 500 then raise exception 'Please write a short reason, 3 to 500 characters.'; end if;
 if p_member_id is null or p_member_id=v_actor then raise exception 'Stewards cannot change their own standing.'; end if;
 if not public.bank_is_confirmed(p_member_id) then raise exception 'Member not found.'; end if;
 perform 1 from public.profiles where id=p_member_id for update;
 v_from:=public.bank_level_of(p_member_id);
 if public.bank_level_rank(p_level)<>public.bank_level_rank(v_from)+1 then
   raise exception 'Standing moves up one step at a time, and is never lowered here. To stop someone while a concern is looked at, pause their standing.';
 end if;
 if public.bank_is_paused(p_member_id) then raise exception 'This member''s standing is paused. Lift the pause first.'; end if;
 if p_level='known' and not public.bank_known_ready(p_member_id) then
   raise exception 'This member does not meet the Known conditions yet.';
 end if;
 if p_level='steward' then
   select count(*) into v_noms from public.steward_nominations n
   where n.member_id=p_member_id and public.bank_is_active_steward(n.nominated_by);
   if v_noms<2 then raise exception 'A new steward needs nominations from two current stewards.'; end if;
   select n.created_at into v_second from public.steward_nominations n
   where n.member_id=p_member_id and public.bank_is_active_steward(n.nominated_by)
   order by n.created_at offset 1 limit 1;
   if v_second > now()-interval '14 days' then raise exception 'The two-week waiting period has not ended yet.'; end if;
   if exists(select 1 from public.concerns c where c.about_id=p_member_id and c.status<>'closed') then
     raise exception 'There is an open concern about this member.';
   end if;
 end if;
 insert into public.member_standing(user_id,level,since,granted_by,introduced_by,introduced_at,steward_renew_by)
 values(p_member_id,p_level,now(),v_actor,
        case when p_level='introduced' then v_actor end,
        case when p_level='introduced' then now() end,
        case when p_level='steward' then (now()+interval '1 year')::date end)
 on conflict (user_id) do update set level=excluded.level,since=excluded.since,granted_by=excluded.granted_by,
   introduced_by=coalesce(public.member_standing.introduced_by,excluded.introduced_by),
   introduced_at=coalesce(public.member_standing.introduced_at,excluded.introduced_at),
   steward_renew_by=excluded.steward_renew_by;
 insert into public.standing_events(member_id,kind,from_level,to_level,changed_by,reason)
 values(p_member_id,'level',v_from,p_level,v_actor,v_reason);
 if p_level='steward' then delete from public.steward_nominations where member_id=p_member_id; end if;
 insert into public.notifications(user_id,title,body)
 values(p_member_id,'Your standing changed',
        case p_level when 'introduced' then 'A steward marked you as Introduced.'
                     when 'known' then 'A steward confirmed you as a Known neighbor.'
                     else 'You are now a steward. Thank you for taking this on.' end);
 return p_member_id;
end $$;

create or replace function public.bank_nominate_steward(p_member_id uuid,p_reason text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_require_steward(); v_reason text := btrim(coalesce(p_reason,'')); v_count integer;
begin
 if char_length(v_reason) not between 3 and 500 then raise exception 'Please write a short reason, 3 to 500 characters.'; end if;
 if p_member_id is null or p_member_id=v_actor then raise exception 'Stewards cannot nominate themselves.'; end if;
 if public.bank_level_of(p_member_id)<>'known' or public.bank_is_paused(p_member_id) then
   raise exception 'Only a Known neighbor can be nominated as a steward.';
 end if;
 perform 1 from public.profiles where id=p_member_id for update;
 insert into public.steward_nominations(member_id,nominated_by,reason)
 values(p_member_id,v_actor,v_reason) on conflict do nothing;
 if not found then raise exception 'You already nominated this member.'; end if;
 select count(*) into v_count from public.steward_nominations n
 where n.member_id=p_member_id and public.bank_is_active_steward(n.nominated_by);
 if v_count=1 then
   insert into public.notifications(user_id,title,body)
   values(p_member_id,'You were nominated as a steward','A steward nominated you. A second steward''s nomination starts a two-week waiting period.');
 elsif v_count=2 then
   -- The waiting period exists so anyone can raise a private concern first.
   insert into public.notifications(user_id,title,body)
   select p.id,'A neighbor was nominated as a steward',
          coalesce((select username from public.profiles where id=p_member_id),'A member')||
          ' was nominated as a steward. If you have a concern, tell a steward or the coordinator privately in the next two weeks.'
   from public.profiles p join auth.users u on u.id=p.id
   where u.email_confirmed_at is not null and p.id<>p_member_id;
 end if;
 return p_member_id;
end $$;

-- Renewal is recorded, never automatic. Lapsing is not a silent removal.
create or replace function public.bank_renew_steward(p_member_id uuid,p_reason text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_require_steward(); v_reason text := btrim(coalesce(p_reason,''));
begin
 if char_length(v_reason) not between 3 and 500 then raise exception 'Please write a short reason, 3 to 500 characters.'; end if;
 if p_member_id is null or p_member_id=v_actor then raise exception 'Another steward renews you.'; end if;
 update public.member_standing set steward_renew_by=(now()+interval '1 year')::date
 where user_id=p_member_id and level='steward';
 if not found then raise exception 'This member is not a steward.'; end if;
 insert into public.standing_events(member_id,kind,from_level,to_level,changed_by,reason)
 values(p_member_id,'renewal','steward','steward',v_actor,v_reason);
 return p_member_id;
end $$;

-- Conduct only: the form asks what happened and what the person did.
create or replace function public.bank_raise_concern(p_about_id uuid,p_exchange_id bigint,p_body text,p_share_name boolean)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_actor(); e public.exchanges%rowtype; v_about uuid := p_about_id; v_id bigint;
begin
 if char_length(btrim(coalesce(p_body,''))) not between 10 and 4000 then raise exception 'Please write 10 to 4000 characters.'; end if;
 if p_share_name is null then raise exception 'Choose whether your name may be shared.'; end if;
 if p_exchange_id is not null then
   select * into e from public.exchanges where id=p_exchange_id;
   if not found or v_actor not in (e.provider_id,e.requester_id) then raise exception 'Exchange not found'; end if;
   if v_about is null then v_about:=case when v_actor=e.provider_id then e.requester_id else e.provider_id end;
   elsif v_about not in (e.provider_id,e.requester_id) then raise exception 'That member is not part of this exchange.'; end if;
 end if;
 if v_about is not null and (v_about=v_actor or not exists(select 1 from public.profiles where id=v_about)) then
   raise exception 'Member not found.';
 end if;
 insert into public.concerns(reporter_id,about_id,exchange_id,body,share_name)
 values(v_actor,v_about,p_exchange_id,btrim(p_body),p_share_name) returning id into v_id;
 perform public.bank_notify_stewards('A private concern needs a steward',
   'Please write back to the member within two days.',array[v_actor,v_about]);
 return v_id;
end $$;

create or replace function public.bank_respond_concern(p_id bigint,p_response text,p_note text,p_close boolean)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_require_steward(); c public.concerns%rowtype;
        v_response text := nullif(btrim(coalesce(p_response,'')),''); v_note text := nullif(btrim(coalesce(p_note,'')),'');
begin
 select * into c from public.concerns where id=p_id for update;
 if not found or c.about_id is not distinct from v_actor then raise exception 'Concern not found.'; end if;
 if c.reporter_id=v_actor then raise exception 'Another steward should answer a concern you raised.'; end if;
 if c.status='closed' then raise exception 'This concern is closed.'; end if;
 if v_response is null and v_note is null and not coalesce(p_close,false) then raise exception 'Write a reply or a note, or close the concern.'; end if;
 if char_length(coalesce(v_response,''))>2000 or char_length(coalesce(v_note,''))>4000 then raise exception 'That text is too long.'; end if;
 if v_note is not null then
   insert into public.concern_notes(concern_id,steward_id,body) values(p_id,v_actor,v_note);
 end if;
 update public.concerns set
   response=coalesce(v_response,response),
   responded_by=case when v_response is not null then v_actor else responded_by end,
   responded_at=case when v_response is not null then now() else responded_at end,
   status=case when coalesce(p_close,false) then 'closed' when v_response is not null then 'responded' else status end,
   closed_at=case when coalesce(p_close,false) then now() else closed_at end
 where id=p_id;
 if v_response is not null or coalesce(p_close,false) then
   insert into public.notifications(user_id,title,body)
   values(c.reporter_id,'A steward answered your concern','Open your dashboard to read the reply.');
 end if;
 return p_id;
end $$;

-- A pause is never silent: the member is told, and told who to call.
create or replace function public.bank_pause_standing(p_member_id uuid,p_reason text,p_concern_id bigint)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_require_steward(); v_reason text := btrim(coalesce(p_reason,''));
begin
 if char_length(v_reason) not between 3 and 500 then raise exception 'Please write a short reason, 3 to 500 characters.'; end if;
 if p_member_id is null or p_member_id=v_actor then raise exception 'Stewards cannot pause themselves.'; end if;
 if not public.bank_is_confirmed(p_member_id) then raise exception 'Member not found.'; end if;
 if p_concern_id is not null and not exists(select 1 from public.concerns where id=p_concern_id and about_id=p_member_id) then
   raise exception 'That concern is not about this member.';
 end if;
 insert into public.standing_pauses(member_id,paused_by,concern_id,reason)
 values(p_member_id,v_actor,p_concern_id,v_reason) on conflict do nothing;
 if not found then raise exception 'This member''s standing is already paused.'; end if;
 insert into public.standing_events(member_id,kind,from_level,to_level,changed_by,reason)
 values(p_member_id,'pause',public.bank_level_of(p_member_id),public.bank_level_of(p_member_id),v_actor,v_reason);
 insert into public.notifications(user_id,title,body)
 values(p_member_id,'A steward has asked to talk with you before your next exchange',
        'Please reach out to '||coalesce((select username from public.profiles where id=v_actor),'a steward')||'. Your dashboard says more.');
 return p_member_id;
end $$;

create or replace function public.bank_unpause_standing(p_member_id uuid,p_reason text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := public.bank_require_steward(); v_reason text := btrim(coalesce(p_reason,''));
begin
 if char_length(v_reason) not between 3 and 500 then raise exception 'Please write a short reason, 3 to 500 characters.'; end if;
