 insert into public.standing_events(member_id,kind,from_level,to_level,changed_by,reason)
 values(p_member_id,'unpause',public.bank_level_of(p_member_id),public.bank_level_of(p_member_id),v_actor,v_reason);
 insert into public.notifications(user_id,title,body)
 values(p_member_id,'Your pause was lifted','You can start new exchanges again.');
 return p_member_id;
end $$;

-- What any signed-in member may see about another member's standing. Pauses,
-- reasons, and concerns are not part of it.
create or replace function public.bank_member_standing()
returns table(user_id uuid,level text,since timestamptz,introduced_by uuid,introduced_at timestamptz,
              gathering_title text,gathering_starts_at timestamptz,joined_at timestamptz,
              completed_exchanges bigint,exchange_partners bigint,steward_renew_by date)
language plpgsql stable security definer set search_path = '' as $$
#variable_conflict use_column
begin
 perform public.bank_actor();
 return query
 select p.id,coalesce(s.level,'new'),coalesce(s.since,p.created_at),s.introduced_by,s.introduced_at,
        g.title,g.starts_at,p.created_at,coalesce(x.n,0)::bigint,coalesce(x.partners,0)::bigint,s.steward_renew_by
 from public.profiles p
 join auth.users u on u.id=p.id and u.email_confirmed_at is not null
 left join public.member_standing s on s.user_id=p.id
 left join public.gatherings g on g.id=s.introduced_gathering_id
 left join lateral (
   select count(*) as n,
          count(distinct case when e.provider_id=p.id then e.requester_id else e.provider_id end) as partners
   from public.exchanges e where e.status='completed' and p.id in (e.provider_id,e.requester_id)
 ) x on true;
end $$;

