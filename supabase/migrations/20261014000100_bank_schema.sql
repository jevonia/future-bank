create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  avatar_url text,
  time_balance numeric(10,2) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.profiles add column if not exists username text;
alter table public.profiles add column if not exists avatar_url text;
alter table public.profiles add column if not exists time_balance numeric(10,2) default 0;
alter table public.profiles add column if not exists created_at timestamptz default now();
alter table public.profiles add column if not exists updated_at timestamptz default now();
do $$ begin
 if not exists(select 1 from pg_constraint where conrelid='public.profiles'::regclass and conname='bank_username_format') then
   alter table public.profiles add constraint bank_username_format
     check (username ~ '^[A-Za-z0-9_]{3,20}$') not valid;
 end if;
end $$;
-- Older signups may have auth rows but no profile because the old client
-- created profiles lazily. Backfill them at zero, then import opening entries.
do $$ declare r record; v_attempt integer; begin
 for r in select u.id,u.raw_user_meta_data from auth.users u
          where not exists(select 1 from public.profiles p where p.id=u.id) loop
   for v_attempt in 0..20 loop
     begin
       insert into public.profiles(id,username,avatar_url,time_balance)
       values(r.id,'member_'||substr(md5(r.id::text||':'||v_attempt::text),1,13),
              r.raw_user_meta_data->>'avatar_url',0);
       exit;
     exception when unique_violation then
       if v_attempt=20 then raise; end if;
     end;
   end loop;
 end loop;
end $$;

