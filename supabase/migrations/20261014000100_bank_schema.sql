             'exchanges','exchange_messages','ledger_entries','notifications','kudos',
             'community_fund','fund_requests','projects','project_contributions','transactions','legacy_exchanges','bank_operation_keys']) loop
    execute format('drop policy %I on %I.%I',r.policyname,r.schemaname,r.tablename);
  end loop;
end $$;

