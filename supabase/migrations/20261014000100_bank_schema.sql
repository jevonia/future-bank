create or replace function public.bank_is_member()
returns boolean language sql stable security definer set search_path = '' as $$
  select auth.uid() is not null and exists (
    select 1 from auth.users u where u.id=auth.uid() and u.email_confirmed_at is not null
  )
$$;
create or replace function public.bank_actor()
returns uuid language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.bank_is_member() then raise exception 'Confirmed sign-in required' using errcode='28000'; end if;
  return auth.uid();
end $$;
create or replace function public.bank_is_facilitator()
returns boolean language sql stable security definer set search_path = '' as $$
 select public.bank_is_member() and exists (
   select 1 from public.member_roles r where r.user_id=auth.uid() and r.role='facilitator'
 )
$$;

