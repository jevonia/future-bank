-- PostgreSQL table grants and RLS both apply. No direct member writes except
-- two profile columns. Ordinary members cannot alter roles or account state.
revoke all on public.profiles,public.offers,public.wants,public.accounts,
  public.member_preferences,public.member_roles,public.exchanges,
  public.exchange_messages,public.ledger_entries,public.notifications,
  public.kudos,public.community_fund,public.fund_requests,public.projects,public.bank_operation_keys,
  public.project_contributions from public,anon,authenticated;
-- REVOKE on a table does not remove older column-level privileges.
do $$ declare r record; begin
 for r in select c.relname,a.attname from pg_class c
          join pg_namespace n on n.oid=c.relnamespace
          join pg_attribute a on a.attrelid=c.oid and a.attnum>0 and not a.attisdropped
          where n.nspname='public' and c.relname=any(array[
            'profiles','offers','wants','accounts','member_preferences','member_roles',
            'exchanges','exchange_messages','ledger_entries','notifications','kudos',
            'community_fund','fund_requests','projects','project_contributions','bank_operation_keys',
            'transactions','legacy_exchanges']) loop
   execute format('revoke select (%1$I), insert (%1$I), update (%1$I), references (%1$I) on public.%2$I from public,anon,authenticated',
                  r.attname,r.relname);
 end loop;
end $$;
grant select(id,username,avatar_url) on public.profiles to authenticated;
