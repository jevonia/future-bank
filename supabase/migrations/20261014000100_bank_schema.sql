-- An earlier unversioned design used time_credits and unrestricted writes.
-- Keep its rows intact under a legacy name; the new exchange table is exact minutes.
do $$ begin
 if to_regclass('public.exchanges') is not null
    and exists(select 1 from information_schema.columns
               where table_schema='public' and table_name='exchanges' and column_name='time_credits')
    and not exists(select 1 from information_schema.columns
                   where table_schema='public' and table_name='exchanges' and column_name='minutes') then
   if to_regclass('public.legacy_exchanges') is not null then
     raise exception 'legacy_exchanges already exists; review legacy exchange migration manually';
   end if;
   alter table public.exchanges rename to legacy_exchanges;
 end if;
end $$;
create table if not exists public.exchanges (
  id bigint generated by default as identity primary key,
  offer_id bigint references public.offers(id) on delete set null,
  want_id bigint references public.wants(id) on delete set null,
  provider_id uuid not null references public.profiles(id),
  requester_id uuid not null references public.profiles(id),
  initiator_id uuid not null references public.profiles(id),
  title text not null,
  category text,
  minutes integer not null check (minutes between 1 and 2880),
  status text not null default 'pending' check (status in ('pending','accepted','completed','cancelled','declined')),
  provider_confirmed boolean not null default false,
  requester_confirmed boolean not null default false,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  check (provider_id <> requester_id),
  check (initiator_id in (provider_id,requester_id))
);
