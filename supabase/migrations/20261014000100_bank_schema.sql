end $$;
-- Revoke only sequences owned by bank tables; leave unrelated public objects alone.
do $$ declare r record; begin
 for r in select sn.nspname as sequence_schema,s.relname as sequence_name
          from pg_class s
          join pg_namespace sn on sn.oid=s.relnamespace
          join pg_depend d on d.objid=s.oid and d.deptype in ('a','i')
          join pg_class t on t.oid=d.refobjid
          join pg_namespace tn on tn.oid=t.relnamespace
          where s.relkind='S' and sn.nspname='public' and tn.nspname='public'
            and t.relname=any(array['offers','wants','exchanges','legacy_exchanges','transactions',
              'exchange_messages','ledger_entries','notifications','kudos','fund_requests',
              'projects','project_contributions']) loop
   execute format('revoke all on sequence %I.%I from public,anon,authenticated',r.sequence_schema,r.sequence_name);
 end loop;
end $$;
revoke all on function public.bank_handle_new_user() from public,anon,authenticated;
revoke all on function public.bank_is_member(), public.bank_actor(), public.bank_is_facilitator() from public,anon;
grant execute on function public.bank_is_member(), public.bank_actor(), public.bank_is_facilitator() to authenticated;
commit;
