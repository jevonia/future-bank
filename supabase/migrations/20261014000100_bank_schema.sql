-- Existing profiles retain their legacy source balance. Fractional-minute
-- values require a reviewed conversion decision before this migration runs.
-- Opening entries make every imported account auditable, including zero balances.
do $$ begin
 if exists(select 1 from public.profiles p where p.time_balance<0 and
           not exists(select 1 from public.accounts a where a.user_id=p.id)) then
   raise exception 'Negative legacy balance found; resolve before minute conversion';
 end if;
 if exists(select 1 from public.profiles p where
           p.time_balance is not null and
           p.time_balance::numeric * 60 <> trunc(p.time_balance::numeric * 60) and
           not exists(select 1 from public.accounts a where a.user_id=p.id)) then
   raise exception 'Fractional-minute legacy balance found; resolve before exact conversion';
 end if;
end $$;
insert into public.accounts(user_id,balance_minutes)
select id, (coalesce(time_balance,0)::numeric * 60)::integer
from public.profiles
on conflict (user_id) do nothing;
insert into public.ledger_entries(user_id,amount_minutes,balance_after_minutes,kind,description)
select a.user_id,a.balance_minutes,a.balance_minutes,'opening',
       'Imported opening balance; legacy profile time_balance retained as source'
from public.accounts a
where not exists (select 1 from public.ledger_entries l where l.user_id=a.user_id and l.kind in ('opening','welcome'));
insert into public.member_preferences(user_id)
select id from public.profiles on conflict (user_id) do nothing;

create or replace function public.bank_handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_name text; v_requested text; v_attempt integer;
begin
  v_requested := new.raw_user_meta_data->>'username';
  for v_attempt in 0..20 loop
    if v_attempt=0 and v_requested ~ '^[A-Za-z0-9_]{3,20}$' then
      v_name:=v_requested;
    else
      v_name:='member_' || substr(md5(new.id::text||':'||v_attempt::text),1,13);
    end if;
    begin
      insert into public.profiles(id,username,avatar_url,time_balance)
      values(new.id,v_name,new.raw_user_meta_data->>'avatar_url',0);
      exit;
    exception when unique_violation then
      if v_attempt=20 then raise; end if;
    end;
  end loop;
  insert into public.accounts(user_id,balance_minutes) values(new.id,120);
  insert into public.ledger_entries(user_id,amount_minutes,balance_after_minutes,kind,description)
  values(new.id,120,120,'welcome','Two-hour welcome grant');
  insert into public.member_preferences(user_id) values(new.id);
  return new;
end $$;
do $$ declare r record; begin
 for r in select t.tgname from pg_trigger t
          join pg_proc p on p.oid=t.tgfoid
          join pg_namespace n on n.oid=p.pronamespace
          where t.tgrelid='auth.users'::regclass and not t.tgisinternal
            and n.nspname='public' and p.proname='handle_new_user' loop
   execute format('drop trigger %I on auth.users',r.tgname);
 end loop;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.bank_handle_new_user();

-- If an older exchange design was installed, retain its records and remove
-- executable legacy credit paths. They are not migrated silently.
do $$ declare r record; begin
  for r in select p.oid::regprocedure as signature
           from pg_proc p join pg_namespace n on n.oid=p.pronamespace
           where n.nspname='public' and p.proname in
           ('create_exchange_request','accept_exchange_request','decline_exchange_request',
            'complete_exchange','cancel_exchange_request','cancel_exchange','handle_new_user') loop
    execute format('revoke all on function %s from public, anon, authenticated',r.signature);
  end loop;
end $$;

